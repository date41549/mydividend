export function lookupStock(code: string): StockDirEntry | undefined {
  const c = code.trim();
  if (!c) return undefined;
  const hit = STOCK_DIRECTORY[c];
  if (!hit || !hit.name) return undefined; // placeholder guard を除外
  return hit;
}
